import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const wasmFiles = ['z80-single.wasm', 'z80-shared.wasm'].map(name => ({ name, bytes: fs.readFileSync(path.join(root, 'public', name)) }));
for (const wasm of wasmFiles) if (wasm.bytes.length < 10000) throw new Error(`${wasm.name} is unexpectedly small`);
console.log(`WebAssembly assets valid: ${wasmFiles.map(x => `${x.name}=${x.bytes.length} bytes`).join(', ')}.`);
const snapshot = fs.statSync(path.join(root, 'public', 'starquake.sna')).size;
const rom = fs.statSync(path.join(root, 'public', '48.rom')).size;
if (snapshot !== 49179) throw new Error(`starquake.sna must be 49,179 bytes; got ${snapshot}`);
if (rom < 16384) throw new Error(`48.rom must be at least 16,384 bytes; got ${rom}`);
console.log(`Bundled game assets valid: starquake.sna=${snapshot} bytes, 48.rom=${rom} bytes.`);
